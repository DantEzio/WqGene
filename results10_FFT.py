# ---- (b) row 1, col 2: absolute-error Bollinger bands (computation and styling copied from results2_trans_test_Bollinger.py) ----
ax_band = fig.add_subplot(gs[0, 1])
if row1_model in model_data:
    errors = model_data[row1_model]['errors']   # per-step absolute error (MAE)

    # Bollinger band computation (same as calculate_bollinger_bands in results2:
    # Window of 40 including the current point; np.mean + np.std (population std, ddof=0); the first window-1 points are NaN)
    bb_window = 40
    num_std = 3
    upper_band, middle_band, lower_band = [], [], []
    for i in range(len(errors)):
        if i < bb_window - 1:
            upper_band.append(np.nan)
            middle_band.append(np.nan)
            lower_band.append(np.nan)
        else:
            window_errors = errors[i - bb_window + 1: i + 1]
            mean_error = np.mean(window_errors)
            std_error = np.std(window_errors)   # population std (ddof=0), same as results2 / the transfer trigger logic
            upper_band.append(mean_error + num_std * std_error)
            middle_band.append(mean_error)
            lower_band.append(mean_error - num_std * std_error)
    upper_band = np.array(upper_band)
    middle_band = np.array(middle_band)
    lower_band = np.array(lower_band)

    # Date series (only for x tick labels, converted like results2)
    actual_dates = get_actual_dates()
    start_idx = int(0.3 * (len(actual_dates) - bb_window))
    dates = [actual_dates[start_idx + s] for s in range(len(errors))]

    time_steps = range(len(errors))

    # Filled band plus the middle line (drawn like results2, without the raw error line)
    ax_band.fill_between(time_steps, lower_band, upper_band,
                         color=model_colors[row1_model]['light'], alpha=0.7,
                         label='Absolute Error Bands Range')
    ax_band.plot(time_steps, middle_band,
                 color=model_colors[row1_model]['main'], linewidth=2,
                 label='Middle Band (Mean Absolute Error)')

    # Mark the highest middle-band point on 2025-08-02 (consistent with results2)
    target_date = '2025-08-02'
    target_date_points = []
    for i, date in enumerate(dates):
        date_str = date.strftime('%Y-%m-%d') if hasattr(date, 'strftime') else str(date)
        if date_str == target_date and i < len(middle_band):
            value = middle_band[i]
            if not np.isnan(value):
                target_date_points.append((i, value))
    if target_date_points:
        target_date_points.sort(key=lambda x: x[1], reverse=True)
        highest_idx, highest_value = target_date_points[0]
        ax_band.plot(highest_idx, highest_value, 'o', color='red',
                     markersize=8, alpha=0.8)
