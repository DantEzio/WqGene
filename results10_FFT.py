# Function to calculate absolute errors from the prediction file (consistent with results1)
def calculate_absolute_errors(prediction_path):
    """Calculate absolute errors from prediction file"""
    if not os.path.exists(prediction_path):
        print(f"Warning: Prediction file not found at {prediction_path}")
        return None

    df = pd.read_csv(prediction_path)

    # Extract real and predicted values
    real_cols = [col for col in df.columns if ('true' in col.lower() or 'real' in col.lower())]
    pred_cols = [col for col in df.columns if 'pred' in col.lower()]

    real_values = df[real_cols].values
    pred_values = df[pred_cols].values

    # Mean absolute error over the 12 output dims for each time step
    absolute_errors = np.mean(np.abs(pred_values - real_values), axis=1)

    return absolute_errors


# Function to calculate per-step MSE from prediction file
def calculate_sample_mse(prediction_path):
    """Calculate per-step MSE (mean squared error over the 12 output dims) from the prediction file"""
    if not os.path.exists(prediction_path):
        print(f"Warning: Prediction file not found at {prediction_path}")
        return None

    df = pd.read_csv(prediction_path)

    # Extract real and predicted values
    real_cols = [col for col in df.columns if ('true' in col.lower() or 'real' in col.lower())]
    pred_cols = [col for col in df.columns if 'pred' in col.lower()]

    real_values = df[real_cols].values
    pred_values = df[pred_cols].values

    # Calculate MSE for each time step
    sample_mse = np.mean((pred_values - real_values) ** 2, axis=1)

    return sample_mse


# Function to read the actual dates from wq.xlsx (consistent with results1)
def get_actual_dates():
    """Read the time column of wq.xlsx as the actual date series"""
    try:
        df = pd.read_excel('data_WQ/wq.xlsx')
        return pd.to_datetime(df['time']).tolist()
    except FileNotFoundError:
        print("Warning: wq.xlsx not found, generating 15-min timestamps as fallback")
        return pd.date_range(start='2025-05-30', periods=14253, freq='15min').tolist()


