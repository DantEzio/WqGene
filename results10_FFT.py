    ax_band.legend(loc='upper right', fontsize=label_size)
    ax_band.grid(True, alpha=0.15)
    ax_band.set_ylim(bottom=0, top=0.25)   # same as results2: lower 0, upper 0.25

    # Show only 3 evenly spaced date ticks on the x axis (consistent with results2)
